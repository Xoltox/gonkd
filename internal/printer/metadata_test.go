func TestSDFileMetaJSONOmitsEmptyFields(t *testing.T) {
	// A zero-value SDMeta must marshal to "{}" (every field omitempty), so
	// SDFile.Meta only ever adds bytes to the response when there's
	// something to say.
	data, err := json.Marshal(SDMeta{})
	if err != nil {
		t.Fatal(err)
	}
	if strings.TrimSpace(string(data)) != "{}" {
		t.Fatalf("empty SDMeta marshaled to %q, want {}", data)
	}
}

func TestMetaPauseMessageIgnoresComment(t *testing.T) {
	p := &metaParser{}
	var off int64
	for _, l := range []string{"M117 Swap to red", "M0 ; Pause and wait for click", "M0 Load white ; comment"} {
		p.feed(l, off)
		off += int64(len(l)) + 1
	}
	m, _ := p.result()
	if len(m.Pauses) != 2 || m.Pauses[0].Msg != "Swap to red" || m.Pauses[1].Msg != "Load white" {
		t.Fatalf("pauses = %+v", m.Pauses)
	}
}
